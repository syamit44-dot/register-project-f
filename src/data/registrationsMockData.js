const ACCESSORY_POOL = [
  "Humidity Sensor",
  "Temperature",
  "Ammonia",
  "Carbon Dioxide",
  "Static Pressure",
  "Phase Protection PVM 4",
];

function pickAccessories(seed, i) {
  return ACCESSORY_POOL.filter((_, idx) => (seed + i + idx) % 3 === 0);
}

function houses(prefix, count, deviceModel, { firmware = "v2.4.0", installDate, lastSync } = {}) {
  return Array.from({ length: count }, (_, i) => ({
    id: `${prefix}-H${i + 1}`,
    name: `House ${i + 1}`,
    serial_number: `SN-2026-${prefix}${String(i + 1).padStart(2, "0")}`,
    device_model: deviceModel,
    firmware_version: firmware,
    install_date: installDate,
    last_sync: lastSync,
    accessories: pickAccessories(prefix.length, i),
  }));
}

// TempView ไม่ผูก S/N รายโรงเรือน (ตรงกับฝั่งลูกค้าที่ไม่ส่ง houses มาสำหรับ platform นี้)
function housesNoSerial(prefix, count, deviceModel, { firmware = "v2.4.0", installDate, lastSync } = {}) {
  return Array.from({ length: count }, (_, i) => ({
    id: `${prefix}-H${i + 1}`,
    name: `House ${i + 1}`,
    device_model: deviceModel,
    firmware_version: firmware,
    install_date: installDate,
    last_sync: lastSync,
    accessories: pickAccessories(prefix.length, i),
  }));
}

function users(names) {
  return names.map((n, i) => ({
    id: `U${i + 1}`,
    username: n.username,
    user_type: n.user_type,
  }));
}

